import { chromium } from 'playwright';
import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path';
const ROOT = path.resolve(import.meta.dirname, '../../public');
const server = http.createServer((q, r) => { const p = path.join(ROOT, decodeURIComponent(q.url.split('?')[0]).replace(/^\/$/, '/index.html')); if (!fs.existsSync(p)) { r.writeHead(404); return r.end(); } r.writeHead(200, { 'content-type': 'text/html; charset=utf-8' }); fs.createReadStream(p).pipe(r); }).listen(0);
const base = `http://127.0.0.1:${server.address().port}`, OUT = path.resolve(import.meta.dirname, '../out/shots');
const b = await chromium.launch(); const pg = await b.newPage({ viewport: { width: 1600, height: 1000 } });
const shot = n => pg.screenshot({ path: `${OUT}/${n}.png` });
await pg.goto(base + '/index.html'); await shot('0-index');
await pg.goto(base + '/talent_hr_admin.html'); await pg.waitForTimeout(300);
await pg.goto(base + '/hr_matching.html'); await shot('1-jd');
await pg.click('#btnAnalyze'); await pg.waitForSelector('#btnGate:not([disabled])'); await shot('2-gate');
await pg.click('#btnGate'); await pg.waitForTimeout(3300); await shot('3-scan');
await pg.waitForSelector('#p4.active', { timeout: 20000 }); await pg.waitForTimeout(500); await shot('4-list');
await pg.locator('.cand', { hasText: '이한결' }).click(); await pg.click('text=제안서 작성 →'); await pg.waitForSelector('#btnSend:not([disabled])', { timeout: 20000 }); await shot('5-offer');
await pg.click('#btnSend');
await pg.goto(base + '/employee.html'); await pg.waitForTimeout(300); await shot('6-emp-home');
await pg.click('#offerBox button.primary'); await pg.waitForTimeout(400); await shot('7-emp-diag');
await pg.evaluate(() => window.scrollTo(0, 700)); await pg.waitForTimeout(300); await shot('8-emp-diag2');
await b.close(); server.close();
